/** @type {ReadonlyArray<{k:string,t:string,num?:boolean}>} num=true ⇒ มีช่องกรอกจำนวน (พาเลท) */
const CHECKLIST = [
  { k: "shelf", t: "ชั้นวางสินค้า — ไม่ชำรุด/เอียง/ล้ม" },
  { k: "clean", t: "ความสะอาดพื้น — ทางเดินโล่ง ไม่มีของกีดขวาง" },
  { k: "fork", t: "รถโฟล์คลิฟท์ — เบรก/แตร/ไฟ ปกติ จอดชาร์จ" },
  { k: "pallet", t: "นับจำนวนพาเลท — ตรงทะเบียน", num: true },
  { k: "fire", t: "ถังดับเพลิง — อยู่ครบ เข็มชี้เขียว" },
  { k: "exit", t: "ทางหนีไฟ/ประตูฉุกเฉิน — ไม่มีของขวาง" },
  { k: "lock", t: "ประตูโกดัง/กุญแจ — ล็อกครบ" },
  { k: "light", t: "ไฟฟ้า/ไฟส่องสว่าง — ปิดจุดที่ไม่ใช้" },
  { k: "cctv", t: "กล้องวงจรปิด — ทำงานครบทุกตัว" },
  { k: "valuable", t: "ของมีค่า/ของเสี่ยง — เก็บเข้าที่ปลอดภัย" },
];

/** คีย์ทั้งหมด — ตัวเขียนใช้กันคีย์แปลกๆ (หมายเหตุของข้อที่ไม่มีอยู่) เข้าฐาน */
const CHECK_KEYS = CHECKLIST.map((it) => it.k);

/**
 * สถานะของ 1 ข้อ — **ตัวตัดสินเดียว** ที่ทั้งจอภูมและหน้าลิงก์เจ้านายใช้ร่วมกัน
 *
 * ภูม 2026-11-21: *"ถ้าสมมุติมันเกิดปัญหาหละ คือไม่ต้องติ๊กหรือไง … ให้ทำเป็นหมายเหตุไว้ได้ไหม"*
 *   "ok"    = ติ๊กแล้ว เรียบร้อย
 *   "issue" = ไม่ติ๊ก แต่เขียนหมายเหตุไว้ ⇒ **ตรวจแล้ว เจอปัญหา** (ไม่ใช่ "ลืมตรวจ")
 *   "todo"  = ยังไม่ได้ตรวจ (ไม่ติ๊ก ไม่มีหมายเหตุ)
 * 🔑 ติ๊กแล้วใส่หมายเหตุด้วยก็ได้ = "ok" + มีหมายเหตุประกอบ (เช่น บุบแต่ใช้ได้ แจ้งซ่อมแล้ว)
 */
function itemState(key, checks, notes) {
  const c = checks && typeof checks === "object" ? checks : {};
  const n = notes && typeof notes === "object" ? notes : {};
  if (c[key]) return "ok";
  if (String(n[key] == null ? "" : n[key]).trim()) return "issue";
  return "todo";
}

/** สรุปทั้งวัน: ok = ผ่าน · issue = เจอปัญหา · todo = ยังไม่ตรวจ · checked = ตรวจแล้ว (ok+issue) */
function summarize(checks, notes, items) {
  const list = items || CHECKLIST;
  let ok = 0, issue = 0, todo = 0;
  list.forEach((it) => {
    const s = itemState(it.k, checks, notes);
    if (s === "ok") ok++; else if (s === "issue") issue++; else todo++;
  });
  return { ok, issue, todo, checked: ok + issue, total: list.length };
}

module.exports = { CHECKLIST, CHECK_KEYS, itemState, summarize };
