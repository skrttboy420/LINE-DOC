//    ⚠️ **ห้ามเปลี่ยนคีย์ k ของข้อเดิม** (เปลี่ยน = ของที่ติ๊กไว้เมื่อวานกลายเป็นข้อที่ไม่มีอยู่)
//    เพิ่มข้อใหม่ = ต่อท้ายด้วยคีย์ใหม่ · เลิกใช้ข้อไหน = เอาออกได้ (ประวัติเก่าจะไม่โชว์ข้อนั้น)
